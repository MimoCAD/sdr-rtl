//! Rust source emission for the generated tables: the header line every
//! file starts with, doc comments, and number formatting that is the
//! same on every run (fixed decimals, no locale, no float shortest-repr
//! surprises).

use std::fmt::Write as _;

use crate::records::Provenance;

/// A generated Rust source file being written.
pub struct Src {
    out: String,
}

impl Src {
    /// The file's first line names the generator, the records and the
    /// harness that wrote them, and says not to edit.
    pub fn new(records: &[&Provenance]) -> Src {
        let mut s = Src { out: String::new() };
        let cites: Vec<String> = records.iter().map(|p| p.cite()).collect();
        let _ = writeln!(
            s.out,
            "// GENERATED by examples/tables from {} — do not edit",
            cites.join(", ")
        );
        s
    }

    pub fn line(&mut self, l: &str) {
        self.out.push_str(l);
        self.out.push('\n');
    }

    pub fn blank(&mut self) {
        self.out.push('\n');
    }

    /// `//!` lines (the module's own doc), one per input line, long
    /// lines wrapped at words.
    pub fn module_doc(&mut self, text: &str) {
        self.comment_lines("//!", text);
    }

    /// `///` lines, one per input line, long lines wrapped at words.
    pub fn doc(&mut self, text: &str) {
        self.comment_lines("///", text);
    }

    fn comment_lines(&mut self, prefix: &str, text: &str) {
        for l in text.lines() {
            if l.is_empty() {
                self.line(prefix);
                continue;
            }
            for w in wrap(l, DOC_WIDTH) {
                self.line(&format!("{prefix} {w}"));
            }
        }
    }

    pub fn finish(self) -> String {
        self.out
    }
}

/// Doc comment text is wrapped to this many characters after the
/// comment marker.
pub const DOC_WIDTH: usize = 72;

/// A line broken at spaces into pieces no longer than `width` (a single
/// word longer than that stands alone).
fn wrap(line: &str, width: usize) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    for word in line.split(' ') {
        if cur.is_empty() {
            cur.push_str(word);
        } else if cur.chars().count() + 1 + word.chars().count() <= width {
            cur.push(' ');
            cur.push_str(word);
        } else {
            out.push(std::mem::take(&mut cur));
            cur.push_str(word);
        }
    }
    if !cur.is_empty() || out.is_empty() {
        out.push(cur);
    }
    out
}

/// An f64 literal with a fixed number of decimals (at least one, so it
/// stays an f64 literal).
pub fn f(x: f64, decimals: usize) -> String {
    let d = decimals.max(1);
    let s = format!("{x:.d$}");
    // "-0.0" reads as a sign where there is none.
    if s.trim_start_matches('-')
        .chars()
        .all(|c| c == '0' || c == '.')
    {
        format!("{:.d$}", 0.0)
    } else {
        s
    }
}

/// `Some(<f>)` / `None`.
pub fn opt_f(x: Option<f64>, decimals: usize) -> String {
    match x {
        Some(v) => format!("Some({})", f(v, decimals)),
        None => "None".into(),
    }
}

/// A string literal (a raw string when it has no `"#`, so the text
/// reads as written).
pub fn s(text: &str) -> String {
    if text.contains("\"#") {
        format!("{text:?}")
    } else {
        format!("r#\"{text}\"#")
    }
}

/// Round to `decimals` places (half away from zero), so a value printed
/// and a value compared are the same number.
pub fn round(x: f64, decimals: i32) -> f64 {
    let k = 10f64.powi(decimals);
    (x * k).round() / k
}

/// The median of a non-empty slice (the mean of the two middle values
/// for an even count).
pub fn median(values: &[f64]) -> f64 {
    let mut v: Vec<f64> = values.to_vec();
    v.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
    let n = v.len();
    if n % 2 == 1 {
        v[n / 2]
    } else {
        (v[n / 2 - 1] + v[n / 2]) / 2.0
    }
}
