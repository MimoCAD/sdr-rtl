use std::path::{Path, PathBuf};

/// The records this generator reads, by file name.
pub const GAIN_COMPARATOR_RECORD: &str = "step4-gain-ladder-comparator.json";
pub const GAIN_LOOP_RECORD: &str = "step4-gain-ladder.json";
pub const TUNE_RECORD: &str = "step4-tune-300.000MHz.json";
/// The undescribed SEL_DIV codes lo-find searched.
pub const LO_FIND_CODES: [u8; 4] = [0b100, 0b101, 0b110, 0b111];

/// A generated file: its name under the output directory and its text.
pub struct Generated {
    pub files: Vec<(String, String)>,
    pub summary: Vec<String>,
}

const MODULES: [&str; 7] = [
    "types",
    "pll",
    "gain",
    "if_filter",
    "band",
    "band_paths",
    "tuner_image",
];

fn mod_rs() -> String {
    let mut s = String::new();
    s.push_str("// GENERATED by examples/tables — do not edit\n");
    s.push_str("//! The tables derived from the bench records (derivation/README.md);\n");
    s.push_str("//! one module per record family, the named types in `types`.\n\n");
    for m in MODULES {
        s.push_str(&format!("pub mod {m};\n"));
    }
    s
}

/// The driver's `src/tables/mod.rs`: the modules it carries
/// ([`driver::LEFT_OUT`] not among them).
fn driver_mod_rs() -> String {
    let mut s = String::new();
    s.push_str("// GENERATED by examples/tables — do not edit\n");
    s.push_str("//! The tables derived from the bench records (derivation/README.md);\n");
    s.push_str("//! one module per record family, the named types in `types`. The\n");
    s.push_str("//! driver's copy (examples/tables/driver.rs): the full record, step\n");
    s.push_str("//! 4f's `band` among it, is derivation/generated.\n\n");
    for m in MODULES
        .iter()
        .filter(|m| !driver::LEFT_OUT.contains(&format!("{m}.rs").as_str()))
    {
        if driver::TEST_ONLY_MODULES.contains(&format!("{m}.rs").as_str()) {
            s.push_str("#[cfg(test)]\n");
        }
        s.push_str(&format!("pub mod {m};\n"));
    }
    s
}

/// The driver's copy of every generated file, by name.
pub fn driver_files(g: &Generated) -> Vec<(String, String)> {
    g.files
        .iter()
        .filter(|(name, _)| !driver::LEFT_OUT.contains(&name.as_str()))
        .map(|(name, text)| {
            (
                name.clone(),
                if name == "mod.rs" {
                    driver_mod_rs()
                } else {
                    driver::subset(name, text)
                },
            )
        })
        .collect()
}

pub fn generate(data: &Path) -> Result<Generated, String> {
    let meter = records::load_meter(data)?;
    let scale = scale::fit(&meter)?;

    let sweep = records::load_pll_sweep(data)?;
    let lo_finds: Vec<records::LoFind> = LO_FIND_CODES
        .iter()
        .map(|&c| records::load_lo_find(data, c))
        .collect::<Result<_, _>>()?;
    let edge = records::load_vco_edge(data)?;
    let pll_t = pll::analyse(&sweep, &lo_finds, &edge)?;

    let comparator = records::load_gain_ladder(data, GAIN_COMPARATOR_RECORD)?;
    let loop_rec = records::load_gain_ladder(data, GAIN_LOOP_RECORD)?;
    let gain_t = gain::analyse(&comparator, &loop_rec, &scale)?;

    let filter = records::load_filter(data)?;
    let filter_t = if_filter::analyse(&filter, &scale)?;

    let band_rec = records::load_band_table(data)?;
    let band_t = band::analyse(&band_rec, &scale)?;

    let paths_runs = band_paths::load(data)?;
    let settle = records::load_path_settle(data)?;
    let paths_t = band_paths::analyse(&paths_runs, &settle, &scale)?;

    let tune = records::load_tune(data, TUNE_RECORD)?;

    let files = vec![
        ("mod.rs".to_string(), mod_rs()),
        (
            "types.rs".to_string(),
            format!(
                "// GENERATED by examples/tables — do not edit\n{}",
                types::TYPES_RS
            ),
        ),
        (
            "pll.rs".to_string(),
            pll::emit(&pll_t, &sweep, &lo_finds, &edge),
        ),
        (
            "gain.rs".to_string(),
            gain::emit(&gain_t, &comparator, &loop_rec, &scale),
        ),
        (
            "if_filter.rs".to_string(),
            if_filter::emit(&filter_t, &filter, &scale),
        ),
        (
            "band.rs".to_string(),
            band::emit(&band_t, &band_rec, &scale),
        ),
        (
            "band_paths.rs".to_string(),
            band_paths::emit(&paths_t, &paths_runs, &settle, &scale),
        ),
        ("tuner_image.rs".to_string(), image::emit(&tune)?),
    ];
    let summary = vec![
        format!(
            "meter scale: {:.1} counts/dB over {} ladder points (zero at {:+.1} dB, largest residual {:.0} counts)",
            scale.counts_per_db, scale.points, scale.zero_at_db, scale.max_residual_counts
        ),
        format!(
            "pll: SEL_DIV {} entries ({} usable), VCO received {:.3}-{:.3} GHz (Nint {}..={}), range {:.2}-{:.2} GHz, {} LO spans, {} unreachable, R2 rows {}, sweep runs {}",
            pll_t.entries.len(),
            pll_t.entries.iter().filter(|e| e.divider.is_some()).count(),
            pll_t.vco_received_hz.0 / 1e9,
            pll_t.vco_received_hz.1 / 1e9,
            pll_t.vco_received_nint.0,
            pll_t.vco_received_nint.1,
            pll_t.vco_range_hz.0 / 1e9,
            pll_t.vco_range_hz.1 / 1e9,
            pll_t.reach.len(),
            pll_t.unreachable.len(),
            pll_t.r2_rows.len(),
            pll_t.sweep_runs.len()
        ),
        format!(
            "gain: {} stages x {} codes",
            gain_t.stages.len(),
            gain::CODES
        ),
        format!(
            "if filter: {} FILT_CODE corners, {} FILT_BW corners, {} HPF codes (max deviation {:.1} dB), reference corner {:.2} MHz",
            filter_t.filt_code.len(),
            filter_t.filt_bw.len(),
            filter_t.hpf.len(),
            filter_t.hpf_max_db,
            filter_t.reference.upper_3db_hz / 1e6
        ),
        format!(
            "band: {} grid points ({} measured, {} readings), {} path segments, {} corner-code segments ({} at {} dB), stage A disagrees at {}",
            band_t.points.len(),
            band_t.measured,
            band_t.readings,
            band_t.path_segments.len(),
            band_t.segments.len(),
            band_t.segments_at_repeatability,
            band::REPEATABILITY_DB,
            band_t.stage_a_disagrees
        ),
        format!(
            "band paths: {} grid points x {} runs ({} readings, {} writes retried), {} segments, runs agree at {}, ties (< {} dB) at {}, dominant kept at {}, run-to-run sd {} dB (worst cell {}), within-seconds sd {} dB",
            paths_t.points.len(),
            paths_t.runs,
            paths_t.readings,
            paths_t.retried_writes,
            paths_t.segments.len(),
            paths_t
                .points
                .iter()
                .filter(|p| p.run_best.iter().all(|b| *b == p.best))
                .count(),
            paths_t.tie_db,
            paths_t
                .points
                .iter()
                .filter(|p| p.margin_db < paths_t.tie_db)
                .count(),
            paths_t
                .points
                .iter()
                .filter(|p| p.tie_kept_dominant)
                .count(),
            paths_t.run_sd_db,
            paths_t.run_sd_worst_db,
            paths_t.settle_sd_db
        ),
        format!("tuner image: {} registers", tune.registers.len()),
    ];
    Ok(Generated { files, summary })
}

pub fn write_all(g: &Generated, out: &Path) -> Result<(), String> {
    write_files(&g.files, out)
}

fn write_files(files: &[(String, String)], out: &Path) -> Result<(), String> {
    std::fs::create_dir_all(out).map_err(|e| format!("{}: {e}", out.display()))?;
    for (name, text) in files {
        let p = out.join(name);
        std::fs::write(&p, text).map_err(|e| format!("{}: {e}", p.display()))?;
    }
    Ok(())
}

fn default_src_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("src")
        .join("tables")
}

fn default_data_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("derivation")
        .join("data")
}

fn default_out_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("derivation")
        .join("generated")
}

fn run() -> Result<(), String> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut data = default_data_dir();
    let mut out = default_out_dir();
    let mut src = default_src_dir();
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--data" => data = PathBuf::from(args.get(i + 1).ok_or("--data needs a directory")?),
            "--out" => out = PathBuf::from(args.get(i + 1).ok_or("--out needs a directory")?),
            "--src" => src = PathBuf::from(args.get(i + 1).ok_or("--src needs a directory")?),
            a => {
                return Err(format!(
                    "unknown option {a}; options: --data DIR | --out DIR | --src DIR"
                ));
            }
        }
        i += 2;
    }
    let g = generate(&data)?;
    write_all(&g, &out)?;
    let ours = driver_files(&g);
    write_files(&ours, &src)?;
    // The crate is held to rustfmt; the driver's copy is written formatted.
    let status = std::process::Command::new("rustfmt")
        .args(["--edition", "2024"])
        .args(ours.iter().map(|(name, _)| src.join(name)))
        .status()
        .map_err(|e| format!("rustfmt: {e}"))?;
    if !status.success() {
        return Err(format!("rustfmt on {}: {status}", src.display()));
    }
    for line in &g.summary {
        println!("{line}");
    }
    for (dir, files) in [(&out, &g.files), (&src, &ours)] {
        for (name, text) in files {
            println!(
                "wrote {} ({} bytes, {} lines)",
                dir.join(name).display(),
                text.len(),
                text.lines().count()
            );
        }
    }
    Ok(())
}

fn main() {
    if let Err(e) = run() {
        eprintln!("tables: {e}");
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn generated() -> Generated {
        generate(&default_data_dir()).expect("the step 4 records generate")
    }

    #[test]
    fn two_runs_write_identical_files() {
        let a = generated();
        let b = generated();
        let base = std::env::temp_dir().join(format!("sdr-rtl-tables-{}", std::process::id()));
        let (da, db) = (base.join("a"), base.join("b"));
        write_all(&a, &da).unwrap();
        write_all(&b, &db).unwrap();
        for (name, _) in &a.files {
            let ta = std::fs::read_to_string(da.join(name)).unwrap();
            let tb = std::fs::read_to_string(db.join(name)).unwrap();
            assert_eq!(ta, tb, "{name} differs between two runs");
            assert!(
                ta.starts_with("// GENERATED by examples/tables"),
                "{name} lacks the header"
            );
        }
        let _ = std::fs::remove_dir_all(&base);
    }

    #[test]
    fn every_table_is_non_empty() {
        let g = generated();
        let text = |name: &str| {
            g.files
                .iter()
                .find(|(n, _)| n == name)
                .map(|(_, t)| t.as_str())
                .unwrap_or_else(|| panic!("{name} not generated"))
        };
        // A `[T; 0]` would be an empty table.
        for (name, _) in &g.files {
            assert!(
                !text(name).contains("; 0] = ["),
                "{name} holds an empty table"
            );
        }
        assert!(text("pll.rs").contains("pub const SEL_DIV: [SelDivEntry; 8]"));
        assert!(text("pll.rs").contains("pub const R2_VCO_INDICATOR: [R2Row; "));
        assert!(text("pll.rs").contains("pub const LO_REACH: [LoReach; "));
        assert!(text("gain.rs").contains("pub const LNA_GAIN_DB: [GainCode; 16]"));
        assert!(text("gain.rs").contains("pub const MIX_GAIN_DB: [GainCode; 16]"));
        assert!(text("gain.rs").contains("pub const VGA_GAIN_DB: [GainCode; 16]"));
        assert!(text("if_filter.rs").contains("pub const FILT_CODE_UPPER_3DB: [FiltCorner; 16]"));
        assert!(text("if_filter.rs").contains("pub const FILT_BW_UPPER_3DB: [FiltCorner; 4]"));
        assert!(text("if_filter.rs").contains("pub const HPF_EFFECT: [HpfEffect; 16]"));
        assert!(text("band.rs").contains("pub const BAND_GRID: [BandPoint; "));
        assert!(text("band.rs").contains("pub const BAND_SEGMENTS: [BandSegment; "));
        assert!(
            text("band.rs").contains("BandEntry::Unmeasured"),
            "step 4f's LO gap is marked"
        );
        assert!(
            text("band_paths.rs").contains("pub const BAND_PATH_GRID: [BandPathPoint; 97]"),
            "step 4f2 measures every grid frequency"
        );
        assert!(text("band_paths.rs").contains("pub const BAND_PATH_SEGMENTS: [BandSegment; "));
        assert!(text("tuner_image.rs").contains("pub const TUNER_IMAGE: [RegisterChoice; 27]"));
    }

    /// findings.md step 4j: "Monotonic in every stage (the mixer's 12-15
    /// within +-1 dB of flat)" at the comparator's 1 dB resolution; step
    /// 4i: the loop meter's two slightly negative steps lie within its
    /// about 1.7 dB two-state quantisation.
    #[test]
    fn gain_tables_are_monotonic_within_resolution() {
        let data = default_data_dir();
        let meter = records::load_meter(&data).unwrap();
        let sc = scale::fit(&meter).unwrap();
        let comparator = records::load_gain_ladder(&data, GAIN_COMPARATOR_RECORD).unwrap();
        let loop_rec = records::load_gain_ladder(&data, GAIN_LOOP_RECORD).unwrap();
        let t = gain::analyse(&comparator, &loop_rec, &sc).unwrap();
        const COMPARATOR_TOLERANCE_DB: i16 = 1;
        const LOOP_TOLERANCE_DB: f64 = 1.7;
        for (name, _, rows, _) in &t.stages {
            let comp: Vec<i16> = rows.iter().filter_map(|r| r.comparator_db).collect();
            assert!(comp.len() >= 15, "{name}: {} comparator values", comp.len());
            for w in comp.windows(2) {
                assert!(
                    w[1] >= w[0] - COMPARATOR_TOLERANCE_DB,
                    "{name}: comparator column steps down by more than {COMPARATOR_TOLERANCE_DB} dB: {comp:?}"
                );
            }
            let lm: Vec<f64> = rows.iter().filter_map(|r| r.loop_meter_db).collect();
            for w in lm.windows(2) {
                assert!(
                    w[1] >= w[0] - LOOP_TOLERANCE_DB,
                    "{name}: loop-meter column steps down by more than {LOOP_TOLERANCE_DB} dB: {lm:?}"
                );
            }
            let run1: Vec<i16> = rows.iter().filter_map(|r| r.comparator_run1_db).collect();
            for w in run1.windows(2) {
                assert!(
                    w[1] >= w[0] - COMPARATOR_TOLERANCE_DB,
                    "{name}: comparator run 1 steps down: {run1:?}"
                );
            }
        }
        // The VGA's code 15 is beyond the measured range: a bound, no value.
        let vga = &t.stages.iter().find(|s| s.0 == "VGA_CODE").unwrap().2;
        assert!(vga[15].comparator_db.is_none() && vga[15].comparator_at_least_db.is_some());
        assert!(vga[..15].iter().all(|r| r.comparator_db.is_some()));
    }

    #[test]
    fn filter_corners_fall_with_the_code() {
        let data = default_data_dir();
        let sc = scale::fit(&records::load_meter(&data).unwrap()).unwrap();
        let t = if_filter::analyse(&records::load_filter(&data).unwrap(), &sc).unwrap();
        // findings.md step 4g: monotonic, about 0.19 MHz per code. The
        // loop's two-state alternation (about 1.7 dB) on the corner's
        // slope (about 13 dB over the 2 MHz past it, 6.5 dB/MHz) moves a
        // corner by up to about 0.3 MHz: three tone steps of slack.
        let slack_hz = 3.0 * 100e3;
        for w in t.filt_code.windows(2) {
            assert!(
                w[1].upper_3db_hz <= w[0].upper_3db_hz + slack_hz,
                "FILT_CODE {} -> {}: {} -> {}",
                w[0].code,
                w[1].code,
                w[0].upper_3db_hz,
                w[1].upper_3db_hz
            );
        }
        // And across the whole range the trend is the document's: the
        // narrowest code is well below the widest.
        assert!(t.filt_code[15].upper_3db_hz < t.filt_code[0].upper_3db_hz - 2.0e6);
        assert!(
            t.filt_bw[0].upper_3db_hz > t.filt_bw[1].upper_3db_hz
                && t.filt_bw[2].upper_3db_hz > t.filt_bw[3].upper_3db_hz
        );
    }
}
