//! The table generator: reads the step 4 bench records under
//! derivation/data and writes Rust source tables into
//! derivation/generated, each file headed with the record and harness
//! it came from. Every number in a generated table is a record value or
//! a stated formula over record values; nothing is typed in.
//!
//! ```text
//! cargo run --release -p sdr-rtl --example tables [-- --data DIR --out DIR]
//! ```
//!
//! Inputs (derivation/data): step4-pll-sweep.jsonl, step4-lo-find-sel1xx.jsonl,
//! step4-meter.json, step4-gain-ladder-comparator.json,
//! step4-gain-ladder.json, step4-filter.jsonl, step4-band-table.jsonl,
//! step4f2-band-paths-run{1,2,3}.jsonl,
//! step4-path-settle.jsonl, step4-tune-300.000MHz.json,
//! step14-vco-edge.jsonl.
//!
//! Outputs (derivation/generated): mod.rs, types.rs, pll.rs, gain.rs,
//! if_filter.rs, band.rs, band_paths.rs, tuner_image.rs. README.md there is written by
//! hand and left alone. Running twice gives identical files. Then the
//! driver's copy into src/tables (`--src DIR`): the same less what the
//! driver never reads (`driver.rs`).

